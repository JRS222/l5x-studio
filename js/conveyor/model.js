  function taperRadiusFromFrustum(opts) {
    const width = Math.max(0.05, num(opts && opts.widthM, 0.6));
    const dSmall = Math.max(0.005, num(opts && opts.smallDiameterM, TAPER_DEFAULTS.smallDiameterM));
    const dLarge = Math.max(0.005, num(opts && opts.largeDiameterM, TAPER_DEFAULTS.largeDiameterM));
    const delta = Math.abs(dLarge - dSmall);
    if (delta <= 0) return null;
    return round(width * (dSmall + dLarge) / (2 * delta), 3);
  }
  /* Backwards-compatible alias. */
  function taperRadiusM(opts) { return taperRadiusFromFrustum(opts); }

  /* Diameter difference required for a requested centreline radius (frustum relation). */
  function requiredTaperDeltaM(opts) {
    const width = Math.max(0.05, num(opts && opts.widthM, 0.6));
    const radius = Math.max(0.05, num(opts && opts.radiusM, 1));
    const diameter = Math.max(0.005, num(opts && opts.diameterM, TAPER_DEFAULTS.smallDiameterM));
    return round(width * diameter / radius, 5);
  }

  /* For a chosen radius: the tapered diameters that achieve it (before standardisation). */
  function taperForRadius(opts) {
    const width = Math.max(0.05, num(opts && opts.widthM, 0.6));
    const radius = Math.max(0.05, num(opts && opts.radiusM, 1));
    const diameter = Math.max(0.005, num(opts && opts.diameterM, TAPER_DEFAULTS.smallDiameterM));
    const delta = width * diameter / radius;
    return {
      smallDiameterM: round(diameter, 4),
      largeDiameterM: round(diameter + delta, 4),
      deltaM: round(delta, 4),
      radiusM: round(radius, 3),
      feasible: delta >= TAPER_LIMITS.minDeltaM && delta <= TAPER_LIMITS.maxDeltaRatio * diameter
    };
  }

  /* Standardized tapers available for a face width -> [{standard, radiusM, ratio}] */
  function standardCurveRadii(widthM) {
    const width = Math.max(0.05, num(widthM, 0.6));
    return TAPER_STANDARDS.map(function (t) {
      const dSmall = TAPER_DEFAULTS.smallDiameterM;
      const dLarge = dSmall + t.deltaM;
      return {
        id: t.id, series: t.series, label: t.label,
        deltaM: t.deltaM, smallDiameterM: round(dSmall, 4), largeDiameterM: round(dLarge, 4),
        widthM: width,
        radiusM: taperRadiusFromFrustum({ widthM: width, smallDiameterM: dSmall, largeDiameterM: dLarge }),
        taperRatio: round(t.deltaM / width, 4),
        coneHalfAngleDeg: round(Math.atan2(t.deltaM, 2 * width) * 180 / Math.PI, 3),
        feasible: t.deltaM >= TAPER_LIMITS.minDeltaM && t.deltaM <= TAPER_LIMITS.maxDeltaRatio * dSmall
      };
    });
  }

  /* Pick the standardized taper whose radius is closest to a requested radius.
     Returns { standard, radiusM, deviationPct, ok } */
  function nearestStandardTaper(widthM, radiusM) {
    const requested = Math.max(0.05, num(radiusM, 1));
    const list = standardCurveRadii(widthM).filter(function (t) { return t.feasible; });
    if (!list.length) return null;
    let best = null;
    list.forEach(function (t) {
      const dev = Math.abs(t.radiusM - requested) / requested * 100;
      if (!best || dev < best.deviationPct) best = { standard: t, radiusM: t.radiusM, deviationPct: round(dev, 2), ok: dev <= TAPER_LIMITS.tolerancePct };
    });
    return best;
  }

