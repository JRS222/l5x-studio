  /* Build the 2D polyline of one segment given a start state.
     Returns { points: [{x,y,z}], end: {x,y,z}, endHeading (rad), arc: {cx,cy,R,startAngle,totalAngle}|null } */
  function buildSegmentPath(seg, start, samplesPerZone) {
    const pts = [];
    const z0 = num(start.z, 0);
    const L = num(seg.lengthM, 1);
    const kind = seg.kind || "straight";
    if (kind === "curve") {
      const total = num(seg.curveDeg, 45) * Math.PI / 180;
      const R = Math.max(0.05, num(seg.radiusM, 1.0));
      const sign = total >= 0 ? 1 : -1;
      const absTotal = Math.abs(total);
      const n = Math.max(6, Math.ceil(absTotal / (Math.PI / 24)));
      const h0 = start.heading;
      // vector from the arc centre to the start point (left turn: centre is left of heading)
      const v0x = sign * R * Math.sin(h0);
      const v0y = -sign * R * Math.cos(h0);
      for (let i = 0; i <= n; i++) {
        const a = total * (i / n);
        const rx = v0x * Math.cos(a) - v0y * Math.sin(a);
        const ry = v0x * Math.sin(a) + v0y * Math.cos(a);
        pts.push({ x: round(start.x + (rx - v0x), 4), y: round(start.y + (ry - v0y), 4), z: z0 });
      }
      return {
        points: pts,
        end: pts[pts.length - 1],
        endHeading: start.heading + total,
        arc: { R: R, sign: sign, total: absTotal }
      };
    }
    if (kind === "spiral") {
      const sp = seg.spiral || {};
      const pitch = Math.max(0.01, num(sp.pitchM, 0.5));
      const height = Math.max(0.01, Math.abs(num(sp.heightM, 2)));
      const dir = (sp.direction === "down") ? -1 : 1;
      const R = Math.max(0.2, num(seg.radiusM, 1.2));
      const turns = height / pitch;
      const total = 2 * Math.PI * turns;      // swept angle (radians)
      const n = Math.max(16, Math.ceil(turns * 32));
      const h0 = start.heading;
      const v0x = R * Math.sin(h0);
      const v0y = -R * Math.cos(h0);
      for (let i = 0; i <= n; i++) {
        const a = total * (i / n);
        const rx = v0x * Math.cos(a) - v0y * Math.sin(a);
        const ry = v0x * Math.sin(a) + v0y * Math.cos(a);
        pts.push({
          x: round(start.x + (rx - v0x), 4),
          y: round(start.y + (ry - v0y), 4),
          z: round(z0 + dir * height * (i / n), 4)
        });
      }
      return {
        points: pts,
        end: pts[pts.length - 1],
        endHeading: start.heading + total,
        arc: { R: R, sign: 1, total: total },
        slopeDeg: spiralSlopeDeg({ pitchM: pitch, radiusM: R }),
        heightM: height, pitchM: pitch, turns: round(turns, 2),
        direction: dir > 0 ? "up" : "down"
      };
    }
    // straight
    const h = start.heading;
    const n = Math.max(2, Math.ceil(L / 0.25));
    for (let i = 0; i <= n; i++) {
      const t = L * (i / n);
      pts.push({
        x: round(start.x + Math.cos(h) * t, 4),
        y: round(start.y + Math.sin(h) * t, 4),
        z: z0
      });
    }
    return { points: pts, end: pts[pts.length - 1], endHeading: h, arc: null };
  }

  /* Cumulative 3D length of a polyline. */
  function polylineLength3D(pts) {
    let len = 0;
    for (let i = 1; i < pts.length; i++) {
      len += Math.hypot(pts[i].x - pts[i - 1].x, pts[i].y - pts[i - 1].y, (pts[i].z || 0) - (pts[i - 1].z || 0));
    }
    return len;
  }
  function polylineLength(pts) { return polylineLength3D(pts); }

  /* Point + tangent angle at distance t along a polyline (2D angle; z interpolated). */
  function pointAtDistance(pts, t) {
    let acc = 0;
    for (let i = 1; i < pts.length; i++) {
      const d = Math.hypot(pts[i].x - pts[i - 1].x, pts[i].y - pts[i - 1].y, (pts[i].z || 0) - (pts[i - 1].z || 0));
      if (acc + d >= t || i === pts.length - 1) {
        const f = d === 0 ? 0 : Math.min(1, Math.max(0, (t - acc) / d));
        return {
          x: pts[i - 1].x + (pts[i].x - pts[i - 1].x) * f,
          y: pts[i - 1].y + (pts[i].y - pts[i - 1].y) * f,
          z: (pts[i - 1].z || 0) + ((pts[i].z || 0) - (pts[i - 1].z || 0)) * f,
          angleDeg: Math.atan2(pts[i].y - pts[i - 1].y, pts[i].x - pts[i - 1].x) * 180 / Math.PI
        };
      }
      acc += d;
    }
    const p = pts[pts.length - 1];
    return { x: p.x, y: p.y, z: p.z || 0, angleDeg: 0 };
  }

  /* Offset a 2D polyline by `dist` (positive = left of travel direction) using ROUND joins.
     This is what gives angled joints a rounded edge. Returns [{x,y,z}] */
  function offsetPolyline(pts, dist) {
    const out = [];
    if (!pts.length) return out;
    function normal(p, q) {
      const dx = q.x - p.x, dy = q.y - p.y;
      const len = Math.hypot(dx, dy) || 1;
      return { x: -dy / len, y: dx / len };
    }
    function addPoint(p) {
      const last = out[out.length - 1];
      if (!last || Math.hypot(last.x - p.x, last.y - p.y) > 1e-4) out.push({ x: round(p.x, 4), y: round(p.y, 4), z: p.z || 0 });
    }
    if (pts.length === 1) { addPoint(pts[0]); return out; }
    const n0 = normal(pts[0], pts[1]);
    addPoint({ x: pts[0].x + n0.x * dist, y: pts[0].y + n0.y * dist, z: pts[0].z });
    for (let i = 1; i < pts.length - 1; i++) {
      const a = pts[i - 1], b = pts[i], c = pts[i + 1];
      const n1 = normal(a, b), n2 = normal(b, c);
      // angle between the two offset directions
      let cross = n1.x * n2.y - n1.y * n2.x;
      let dot = n1.x * n2.x + n1.y * n2.y;
      dot = Math.max(-1, Math.min(1, dot));
      const ang = Math.atan2(cross, dot); // signed turn of the normal
      if (Math.abs(ang) < 1e-4) { addPoint({ x: b.x + n2.x * dist, y: b.y + n2.y * dist, z: b.z }); continue; }
      // round join: arc from p1 to p2 around b with radius |dist|
      const p1 = { x: b.x + n1.x * dist, y: b.y + n1.y * dist };
      const p2 = { x: b.x + n2.x * dist, y: b.y + n2.y * dist };
      const steps = Math.max(3, Math.ceil(Math.abs(ang) / (Math.PI / 18)));
      const sign = dist >= 0 ? 1 : -1;
      for (let s = 0; s <= steps; s++) {
        const t = s / steps;
        const a2 = ang * t;
        // rotate p1 about b
        const vx = p1.x - b.x, vy = p1.y - b.y;
        const sx = vx * Math.cos(a2) - vy * Math.sin(a2);
        const sy = vx * Math.sin(a2) + vy * Math.cos(a2);
        addPoint({ x: b.x + sx, y: b.y + sy, z: b.z });
      }
      if (sign === 0) addPoint(p2);
    }
    const nl = normal(pts[pts.length - 2], pts[pts.length - 1]);
    addPoint({ x: pts[pts.length - 1].x + nl.x * dist, y: pts[pts.length - 1].y + nl.y * dist, z: pts[pts.length - 1].z });
    return out;
  }

