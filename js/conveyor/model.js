/* L5X Studio - conveyor/model.js (Lead). Conveyor design document model: chained geometry
   (straight / curved / spiral segments with angled joints and rounded edges), ZPA zone and
   group allocation, belt conveyor support, scan zones and tray/barcode tracking, plus
   validation. Pure functions only (no DOM) so everything is Node-testable.

   Geometry: segments form a CHAIN. Segment 0 has an absolute position/heading; each following
   segment starts exactly at the previous segment's end (no overlap — this is what makes flow
   continuous). A `turnDeg` on a segment rotates the heading before the segment is laid out
   (angled joint); the outer/inner conveyor edges are generated by offsetting the centreline
   with ROUND joins, so angled joints get a rounded edge automatically.
   Curved segments (kind "curve") are true arcs with a centreline radius and are covered by
   tapered rollers. Spiral segments (kind "spiral") are inclined helices (up/down) with pitch,
   height and slope limits — typically belted.

   Engineering scheme (mirrors the SAMPLE_RLL ZPA project templates):
   - one `NETS[1].ZPA[g]` zone GROUP per <=8 zones and one 1799ER-IQ10XOQ10/A block per group
     (input bits 0..7 = zone sensors, output bits 0..7 = run commands);
   - roller conveyors use the ZPA templates; belt conveyors use a drive (PowerFlex 525 /
     starter) and generate tracking logic instead of per-zone ZPA scan routines;
   - scan zones read tray barcodes and feed a tracking array (barcode + zone position).
*/
