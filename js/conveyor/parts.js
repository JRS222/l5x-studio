  function rollerBrand(pn) {
    if (!pn) return null;
    if (/^(PM|IB|CB|HB|CBM|CBK)/.test(pn)) return "itoh";
    if (/^MR-/i.test(pn)) return "microroll";
    if (/^(RC|RA|GM|FM)/.test(pn) || /^RD/.test(pn)) return "infinidrive";
    return null;
  }

  function parseSeries(pn) {
    if (!pn) return null;
    const s = String(pn).trim();
    /* Legacy MR- prefix -> Microroll alias */
    if (/^MR-/i.test(s)) return "MICROROLL";
    /* Itoh Denki */
    const m = s.match(/^(PM\d{3}[A-Z]{2})/);
    if (m && SERIES_SPECS[m[1]]) return m[1];
    /* InfiniDrive positional: RC/RA/GM + diameter letter */
    const pos = s.match(/^(RC|RA|GM)\s([A-E])\s/);
    if (pos) {
      const diamMap = { A: 48, B: 50, C: 57, D: 60, E: 63 };
      const seriesMap = { "RC-48":"RD48", "RC-50":"RD50", "RC-57":"RD57", "RC-60":"RD60",
                          "RC-63":"RD63", "RA-63":"RD63S", "GM-48":"GM48" };
      const key = pos[1] + "-" + diamMap[pos[2]];
      if (seriesMap[key]) return seriesMap[key];
    }
    /* Direct RD/GM name */
    if (/^(RD48|RD50|RD57|RD60|RD63|RD63S|GM48|FM24095)/.test(s)) {
      return s.match(/^(RD48S?|RD50|RD57|RD60|RD63S?|GM48|FM24095)/)[1];
    }
    return null;
  }

