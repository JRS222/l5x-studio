  /* Tapered idler roller description (all rollers on a curve/spiral are tapered). */
  function describeTaperedIdler(series, widthM, taperInfo) {
    const spec = SERIES_SPECS[series] || {};
    const bf = Math.round(num(widthM, 0.6) * 1000);
    const bits = [brandLabel(spec.brand) + " " + series + " tapered idler roller"];
    if (taperInfo && taperInfo.deltaMm !== null && taperInfo.deltaMm !== undefined) {
      bits.push("taper " + taperInfo.deltaMm + " mm" +
        (taperInfo.standardId ? " (" + taperInfo.standardId + ")" : ""));
    }
    if (taperInfo && taperInfo.radiusM !== null && taperInfo.radiusM !== undefined) {
      bits.push("R" + round(taperInfo.radiusM, 3) + " m");
    }
    bits.push(bf + " mm BF, no motor");
    return bits.join(", ");
  }

  /* Tapered-roller series for a curve/spiral roller segment. Priority:
       1. explicit opts.taperSeries (UI/tests override)
       2. design.defaults.taper.brakingSeries for down spirals, then .series
       3. the model's standard-taper series for this segment (PM486FS / MR-AD-48-/TS)
       4. Itoh when the design motor series is Itoh, else the model taper default. */
  function taperedSeriesFor(design, seg, opts, braking) {
    const defaults = (design && design.defaults) || {};
    const taperConf = defaults.taper || {};
    let raw = null;
    if (opts && opts.taperSeries) raw = opts.taperSeries;
    if (!raw && braking && taperConf.brakingSeries) raw = taperConf.brakingSeries;
    if (!raw && taperConf.series) raw = taperConf.series;
    if (!raw && seg && seg.taper && seg.taper.series) raw = seg.taper.series;
    if (!raw) {
      const base = String(defaults.motorSeries || "");
      if (/^PM486/i.test(base)) raw = base;
      else {
        const M = modelApi();
        raw = (M.TAPER_DEFAULTS && M.TAPER_DEFAULTS.series) || "PM486FS";
      }
    }
    return normalizeTaperSeries(raw);
  }

  function fmtM(value, digits) {
    return String(round(num(value, 0), digits === undefined ? 2 : digits));
  }

  /* Revalidation rules from model v2 carried into the selection warnings:
     non-standard curve radius + taper feasibility, down-spiral braking rollers,
     belt spiral slope limits, and scan-zone/tracking pairing. The model emits its
     own warnings too; these are the purchasing/BOM-facing versions. */
  function collectDesignWarnings(design, computed) {
    const M = modelApi();
    const out = [];
    const maxStdDelta = (M.TAPER_STANDARDS || []).reduce(function (acc, t) {
      return Math.max(acc, num(t.deltaM, 0));
    }, 0);
    (computed.segments || []).forEach(function (seg) {
      const isBelt = seg.conveyorType === "belt";
      const kind = seg.kind || "straight";
      if (!isBelt && seg.taper) {
        const info = taperStandardInfo(seg.taper);
        if (!info.withinTolerance) {
          out.push(seg.name + ": curve radius " + fmtM(seg.radiusM || info.requestedRadiusM, 2) +
            " m is not a standard tapered-roller radius (nearest " +
            (info.standardId || "standard") + " = " + fmtM(info.radiusM, 3) + " m, " +
            (info.deviationPct === null ? "?" : info.deviationPct) +
            "% off) - adjust the radius to the standard value or order a custom taper.");
        }
        if (!info.standardId) {
          out.push(seg.name + ": no standardized tapered roller is available for a " +
            fmtM(seg.widthM, 2) + " m face width - curved roller segments need tapered rollers.");
        }
        const dia = (M.TAPER_DEFAULTS && M.TAPER_DEFAULTS.smallDiameterM) || 0.04826;
        const reqDelta = (M.requiredTaperDeltaM && seg.radiusM)
          ? M.requiredTaperDeltaM({ widthM: seg.widthM, radiusM: seg.radiusM, diameterM: dia }) : null;
        if (reqDelta !== null && reqDelta > maxStdDelta + 1e-9) {
          out.push(seg.name + ": radius " + fmtM(seg.radiusM, 2) + " m requires a " +
            fmtM(reqDelta * 1000, 1) + " mm taper delta, beyond the standardized set (max " +
            fmtM(maxStdDelta * 1000, 0) + " mm) - not producible with standard tapered rollers.");
        }
      }
      if (kind === "spiral" && seg.spiral) {
        const slope = num(seg.spiral.slopeDeg, 0);
        const limits = M.SPIRAL_LIMITS || {};
        if (isBelt) {
          const rec = num(limits.recommendedBeltSlopeDeg, 10);
          const max = num(limits.maxSlopeDeg, 18);
          if (slope > max) {
            out.push(seg.name + ": belt spiral slope " + slope + " deg exceeds the " + max +
              " deg maximum - redesign the spiral (the belt will not track).");
          } else if (slope > rec) {
            out.push(seg.name + ": belt spiral slope " + slope + " deg exceeds the recommended " +
              rec + " deg - verify belt tracking / use a flighted belt with the supplier.");
          }
          if (String(seg.spiral.direction || "up").toLowerCase() === "down") {
            out.push(seg.name + ": down spiral on a belt conveyor - fit a brake/backstop to the drive (the belt will back-drive).");
          }
        } else if (String(seg.spiral.direction || "up").toLowerCase() === "down") {
          out.push(seg.name + ": down spiral requires BRAKING tapered rollers - brake roller and brake driver-card variants selected for this segment.");
        }
      }
    });
    const hasScan = (computed.scannedZones || []).length > 0;
    const tracking = !!(computed.tracking && computed.tracking.enabled);
    if (hasScan && !tracking) {
      out.push("Scan zones are defined but tray tracking is disabled - barcodes will not be tracked.");
    }
    if (tracking && !hasScan) {
      out.push("Tray tracking is enabled but no scan zones are defined - barcodes will never be read.");
    }
    return out;
  }

