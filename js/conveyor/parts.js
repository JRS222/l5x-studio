  /* Tube (drum) length in mm from between-frame length in inches. */
  function lroller(inp) { return Math.round((num(inp.lbf, 0) - 0.78) * MM_PER_IN); }

  /* Derived mechanics: roller body class, static friction, spiral angle, tangential
     force (lbs) and torque (in-lbs). Faithful to the source tool formulas. */
  function calcDerived(inp) {
    inp = inp || {};
    const rollerBody = inp.curveType === "Straight" ? "Straight" : "Tapered";
    const table = MU_TABLE[rollerBody] || {};
    const muStatic = table[inp.packageMaterial] !== undefined ? table[inp.packageMaterial] : 0;
    const hspiral = num(inp.hspiral, 0);
    const pitch = num(inp.pitch, 0);
    let ratio = 0;
    if (hspiral > 0) ratio = pitch / (Math.PI * hspiral);
    else if (pitch > 0) ratio = Infinity;
    const theta = rollerBody === "Tapered" ? Math.atan(ratio) * (180 / Math.PI) : 0;
    const fTangential = num(inp.wlbsMax, 0) * muStatic * Math.cos(theta * Math.PI / 180);
    const torque = fTangential * (num(inp.droller, 0) / 2 * muStatic);
    return { rollerBody, muStatic, theta, fTangential, torque };
  }

  /* Compatibility rules (verbatim behaviour of the source validateRoller):
       - frame length must be within 0.315 in of the requested between-frame length
       - curved (tapered-body) applications need a tapered sleeve roller
       - down-spiral applications need a braking roller
       - standard drive needs O-ring grooves
       - pulley drive is incompatible with tapered rollers */
  function validateRollerReasons(roller, inp, derived) {
    const reasons = [];
    if (!roller) return ["No roller"];
    inp = inp || {};
    derived = derived || {};
    const frame = num(inp.lbf, NaN);
    const ideal = num(roller.idealFrame, NaN);
    if (!isFinite(frame) || !isFinite(ideal)) {
      reasons.push("Frame length unknown (roller ideal frame or requested BF missing)");
    } else if (Math.abs(ideal - frame) > 0.315) {
      reasons.push("Ideal frame length " + ideal + "\" is not within 0.315\" of " + frame + "\" BF");
    }
    if (derived.rollerBody === "Tapered" && !roller.tapered) {
      reasons.push("Tapered roller body required for a curved application");
    }
    if (inp.curveType === "Down Spiral" && !roller.braking) {
      reasons.push("Braking roller required for a down-spiral application");
    }
    if (inp.driveStyle === "Standard" && !roller.grooved) {
      reasons.push("Grooved roller required for standard (O-ring) drive");
    }
    if (inp.driveStyle === "Pulley" && roller.tapered) {
      reasons.push("Tapered roller incompatible with pulley drive");
    }
    return reasons;
  }
  /* Contract API: returns "Valid" / "Invalid" exactly like the source tool. */
  function validateRoller(roller, inp, derived) {
    return validateRollerReasons(roller, inp, derived).length === 0 ? "Valid" : "Invalid";
  }

