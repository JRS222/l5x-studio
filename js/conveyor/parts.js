    const pos = INFINIDRIVE_POSITIONAL[series] || INFINIDRIVE_POSITIONAL.RD48;
    const bf = pad4(Math.round(num(inp.lbf, 0) * MM_PER_IN));
    const groove = opts.groove || (inp.driveStyle === "Pulley" ? "P" : "G");
    const ratio = opts.ratio || "27"; /* mid-torque default from the source tool */
